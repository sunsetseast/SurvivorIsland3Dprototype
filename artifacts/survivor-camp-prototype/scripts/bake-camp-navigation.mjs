import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { CampNavigation } from "../src/game/navigation.ts";
import { BOUNDS } from "../src/game/world.ts";
const start = performance.now(),
  nav = new CampNavigation(1, false),
  x0 = Math.ceil(BOUNDS.minX + 1),
  z0 = Math.ceil(BOUNDS.minZ + 1),
  buf = Buffer.alloc(nav.nodes.length * 11),
  byPosition = new Map(nav.nodes.map((n) => [`${n.x},${n.z}`, n.id]));
for (const n of nav.nodes) {
  const k = n.id * 11;
  buf[k] = n.x - x0;
  buf[k + 1] = n.z - z0;
  buf.writeDoubleLE(n.trail, k + 3);
  [
    [1, 0],
    [0, 1],
    [1, 1],
    [1, -1],
  ].forEach(([dx, dz], i) => {
    if (n.edges.includes(byPosition.get(`${n.x + dx},${n.z + dz}`)))
      buf[k + 2] |= 1 << i;
  });
}
const sources = [
  "src/game/world.ts",
  "src/game/environment/geography.ts",
  "src/game/navigation.ts",
  "src/game/environment/rockCollision.json",
];
const hashes = {};
for (const f of sources) {
  try {
    hashes[f] = createHash("sha256")
      .update(await readFile(f))
      .digest("hex");
  } catch (e) {
    if (e.code !== "ENOENT") throw e;
  }
}
await writeFile(
  "src/game/environment/navigationBake.ts",
  `// Generated by scripts/bake-camp-navigation.mjs. Never hand edit.\nexport const CAMP_NAV_BAKE = ${JSON.stringify({ x0, z0, step: 1, count: nav.nodes.length, data: buf.toString("base64") })};\n`,
);
await writeFile(
  "src/game/environment/navigation-manifest.json",
  JSON.stringify(
    {
      sources: hashes,
      nodes: nav.nodes.length,
      directedEdges: nav.nodes.reduce((s, n) => s + n.edges.length, 0),
      bytes: buf.length,
      method:
        "Exact 0.12m clearSegment validations at bake time; float64 trail costs, symmetric edge masks. Default 1m graph only; custom steps retain construction.",
    },
    null,
    2,
  ) + "\n",
);
console.log({
  nodes: nav.nodes.length,
  ms: performance.now() - start,
  bytes: buf.length,
});
